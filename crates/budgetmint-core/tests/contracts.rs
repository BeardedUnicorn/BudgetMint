/// `export const NAME = value;` lines.
fn constants() -> String {
    let mut out = HEADER.to_string();
    let mut value = |doc: &str, name: &str, value: Value| {
        out.push_str(&format!(
            "\n/** {} */\nexport const {} = {} as const;\n",
            doc, name, value
        ));
    };
    value(
        "Every command core runs, by name.",
        "COMMAND_NAMES",
        json!(COMMAND_NAMES),
    );
    value(
        "The documents' schema: written into each, and one from a newer BudgetMint is held.",
        "BUDGET_SCHEMA",
        json!(BUDGET_SCHEMA),
    );
    value(
        "The payout forecast's contract this BudgetMint reads (TaskMint's).",
        "FORECAST_SCHEMA",
        json!(FORECAST_SCHEMA),
    );
    value(
        "The limits core holds edits to, for the forms to hold them too.",
        "LIMITS",
        json!({
            "MAX_ID_LEN": MAX_ID_LEN,
            "MAX_NAME": MAX_NAME,
            "MAX_CATEGORY": MAX_CATEGORY,
            "MAX_NOTE": MAX_NOTE,
            "MAX_LEADS": MAX_LEADS,
            "MAX_LEAD_DAYS": MAX_LEAD_DAYS,
            "MAX_CENTS": MAX_CENTS,
            "MIN_HORIZON_DAYS": MIN_HORIZON_DAYS,
            "MAX_HORIZON_DAYS": MAX_HORIZON_DAYS,
            "MAX_REMINDER_WINDOW_DAYS": MAX_WINDOW_DAYS,
            "MAX_REMINDERS": MAX_REMINDERS,
            "ESTIMATE_FROM": ESTIMATE_FROM,
        }),
    );
    out
}

fn commands(cfg: &Config) -> String {
    let commands = command_types(cfg);
    let mut uses: BTreeSet<String> = commands
        .iter()
        .flat_map(|command| command.uses.iter().cloned())
        .collect();
    uses.remove("NoArgs");
    let mut out = HEADER.to_string();
    for name in &uses {
        out.push_str(&format!(
            "import type {{ {} }} from \"./{}\";\n",
            name, name
        ));
    }
    out.push_str("\n/** Every command's arguments (`void` for none) and reply. */\nexport interface CommandMap {\n");
    for command in &commands {
        let args = if command.args == "NoArgs" {
            "void"
        } else {
            &command.args
        };
        out.push_str(&format!(
            "  {}: {{ args: {}; reply: {} }};\n",
            command.name, args, command.reply
        ));
    }
    out.push_str(
        "}\n\nexport type CommandName = keyof CommandMap;\n\
         export type CommandArgs<K extends CommandName> = CommandMap[K][\"args\"];\n\
         export type CommandReply<K extends CommandName> = CommandMap[K][\"reply\"];\n",
    );
    out
}

/// The generated type files, by module path.
fn type_modules(dir: &Path, prefix: &str) -> Vec<String> {
    let mut modules = Vec::new();
    let mut entries: Vec<_> = fs::read_dir(dir).unwrap().map(|e| e.unwrap()).collect();
    entries.sort_by_key(|entry| entry.file_name());
    for entry in entries {
        let name = entry.file_name().into_string().unwrap();
        if entry.file_type().unwrap().is_dir() {
            modules.extend(type_modules(&entry.path(), &format!("{}{}/", prefix, name)));
        } else if let Some(stem) = name.strip_suffix(".ts") {
            modules.push(format!("{}{}", prefix, stem));
        }
    }
    modules
}

fn index(types: &[String]) -> String {
    let mut out = HEADER.to_string();
    for module in types {
        let name = module.rsplit('/').next().unwrap();
        out.push_str(&format!(
            "export type {{ {} }} from \"./{}\";\n",
            name, module
        ));
    }
    out.push_str("export type * from \"./commands\";\nexport * from \"./constants\";\n");
    out
}

#[test]
fn contracts_are_generated_from_the_rust() {
    let dir = generated_dir();
    // Start empty, so a type that's gone takes its file with it
    let _ = fs::remove_dir_all(&dir);
    let cfg = Config::new().with_large_int("number").with_out_dir(&dir);

    export_types(&cfg);
    let types = type_modules(&dir, "");
    fs::write(dir.join("constants.ts"), constants()).unwrap();
    fs::write(dir.join("commands.ts"), commands(&cfg)).unwrap();
    fs::write(dir.join("index.ts"), index(&types)).unwrap();

    // Every type a command names was exported
    for command in command_types(&cfg) {
        for name in command.uses.iter().filter(|name| *name != "NoArgs") {
            assert!(
                types.contains(name),
                "{} uses {}, which isn't exported",
                command.name,
                name
            );
        }
    }
}
